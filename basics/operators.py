#Logical Operators

'''

True and True = True
True and False = False
False and True = False
False and False = False

'''

marks = 97

print(marks>96 and marks<=97)
print(marks>96 and marks<97)
print(marks>98 and marks<=97)
print(marks>98 and marks<97)

print("************************************")


'''

True or True = True
True or False = True
False or True = True
False or False = False

'''

print(marks>96 or marks<=97)
print(marks>96 or marks<97)
print(marks>98 or marks<=97)
print(marks>98 or marks<97)

print("************************************")


'''

not(True) = False
not(False) = True

'''

print(not(marks>96))
print(not(marks<97))